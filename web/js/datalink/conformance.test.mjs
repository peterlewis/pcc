// Byte-exact conformance for the Timex Datalink port. Fixtures are the expected byte arrays from
// synthead/timex_datalink_client's own RSpec suite (MIT) — the same values the Ruby library asserts —
// so a pass means our JS emits identical bytes. Run: `node web/js/datalink/conformance.test.mjs`.
import { crc16arc, crcWrap, charsFor, Protocol3, compile } from "./timex-datalink.mjs";

let pass = 0, fail = 0;
const eq = (a, b) => a.length === b.length && a.every((v, i) => v === b[i]);
const hex = (a) => "[" + a.map((v) => "0x" + v.toString(16).padStart(2, "0")).join(", ") + "]";
function check(name, got, want) {
  if (eq(got, want)) { pass++; console.log(`  ok   ${name}`); }
  else { fail++; console.log(`  FAIL ${name}\n       got  ${hex(got)}\n       want ${hex(want)}`); }
}

// 1. CRC-16/ARC anchored to the canonical check value (independent of the wrapper).
const check123 = crc16arc([..."123456789"].map((c) => c.charCodeAt(0)));
check("crc16arc('123456789') === 0xBB3D", [check123], [0xbb3d]);

// Verify a wrapped packet independently: header = len+3, footer = crc(header+payload) as [MSB,LSB].
function assertWrapStructure(name, payloadRaw) {
  const w = crcWrap(payloadRaw);
  const framed = w.slice(0, -2);
  const crc = crc16arc(framed);
  check(`${name}: length header`, [w[0]], [payloadRaw.length + 3]);
  check(`${name}: payload body`, w.slice(1, -2), payloadRaw);
  check(`${name}: crc footer`, w.slice(-2), [(crc >> 8) & 0xff, crc & 0xff]);
}

// 2. Protocol 3 — Start / End (fixed command packets), raw payloads from the specs.
assertWrapStructure("Start", [0x20, 0x00, 0x00, 0x03]);
check("Start.packets", Protocol3.start()[0], crcWrap([0x20, 0x00, 0x00, 0x03]));
check("End.packets", Protocol3.end()[0], crcWrap([0x21]));

// 3. Sync (not CRC-wrapped): 0x78 + 0x55*length + 0xaa*40. (protocol_3/sync_spec.rb, length 200.)
check("Sync(200)", Protocol3.sync({ length: 200 })[0],
  [0x78, ...Array(200).fill(0x55), ...Array(40).fill(0xaa)]);

// 4. Time (protocol_3/time_spec.rb): US/Pacific 2015-10-21 19:28:32, zone 1, 12h, "%_m-%d-%y",
//    name defaults to the zone abbreviation "PDT". Expected RAW payload from the spec:
const TIME_RAW = [0x32, 0x01, 0x20, 0x13, 0x1c, 0x0a, 0x15, 0x0f, 0x19, 0x0d, 0x1d, 0x02, 0x01, 0x00];
const t = { sec: 32, hour: 19, min: 28, month: 10, day: 21, year: 2015, wday: 3 };  // 2015-10-21 = Wed
check("Time.packets (raw)",
  Protocol3.time({ zone: 1, is24h: false, dateFormat: "%_m-%d-%y", time: t, name: "PDT" })[0].slice(1, -2),
  TIME_RAW);
check("Time.packets (full wrapped)",
  Protocol3.time({ zone: 1, is24h: false, dateFormat: "%_m-%d-%y", time: t, name: "PDT" })[0],
  crcWrap(TIME_RAW));
check("Time zone 2",
  Protocol3.time({ zone: 2, is24h: false, dateFormat: "%_m-%d-%y", time: t, name: "PDT" })[0].slice(1, -2),
  [0x32, 0x02, ...TIME_RAW.slice(2)]);

// 5. char encoder spot-check: "PDT" -> p=25(0x19) d=13(0x0d) t=29(0x1d).
check("charsFor('PDT',3,pad)", charsFor("PDT", { length: 3, pad: true }), [0x19, 0x0d, 0x1d]);
check("charsFor('a',3,pad) pads with space(36)", charsFor("a", { length: 3, pad: true }), [10, 36, 36]);

// A model emits packets (number[][]); each fixture gives RAW payloads the Ruby shared example CRC-wraps.
// Compare the flat byte streams so packet nesting can't hide a match.
const checkPk = (name, packets, wantRaws) => check(name, packets.flat(), wantRaws.map(crcWrap).flat());

// 6. SoundOptions (protocol_3/sound_options_spec.rb): [0x71, chime, beep].
checkPk("SoundOptions off", Protocol3.soundOptions({ hourlyChime: false, buttonBeep: false }), [[0x71, 0x00, 0x00]]);
checkPk("SoundOptions chime+beep", Protocol3.soundOptions({ hourlyChime: true, buttonBeep: true }), [[0x71, 0x01, 0x01]]);

